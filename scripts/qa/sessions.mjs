import { app, assert, children, clients, connection, db, go, issueInvite, join, origin, randomUUID, scratch } from './harness.mjs'

const pass=randomUUID()
try {
  let c=await connection(1)
  await c.visible('Entrar no HAVEN')
  await c.click('Tenho um convite')
  await c.fill('[name=invite]',issueInvite(db))
  await c.click('Continuar')
  await c.click('Servidor de contas')
  await c.fill('input[type=url]',origin)
  await c.fill('[name=name]','Sessão')
  await c.fill('[name=handle]','sessao')
  await c.fill('[name=password]',pass)
  await c.click('Criar conta')
  await c.visible('Olá, Sessão.')
  const sessionFile=join(scratch,'account1','haven-session.enc')
  const {readFileSync}=await import('node:fs')
  const encrypted=readFileSync(sessionFile)
  assert.ok(encrypted.length>40)
  assert.ok(!encrypted.includes(Buffer.from(origin)))
  assert.ok(!encrypted.includes(Buffer.from(pass)))
  const first=children.at(-1)
  await c.click('Fechar HAVEN',true).catch(()=>{})
  await go(()=>first.exitCode!==null,'primeira instância encerrada')
  c=await connection(1)
  await c.visible('Olá, Sessão.')
  await c.click('Perfil e ajustes',true)
  await c.click('Encerrar sessão')
  await c.visible('Entrar no HAVEN')
  assert.throws(()=>readFileSync(sessionFile),{code:'ENOENT'})
  assert.equal(db.prepare('SELECT COUNT(*) AS n FROM sessions').get().n,0)
  await c.fill('[name=handle]','sessao')
  await c.fill('[name=password]',pass)
  await c.click('Entrar')
  await c.visible('Olá, Sessão.')
  db.prepare('DELETE FROM sessions').run()
  const second=children.at(-1)
  await c.click('Fechar HAVEN',true).catch(()=>{})
  await go(()=>second.exitCode!==null,'segunda instância encerrada')
  c=await connection(1)
  await c.visible('Entrar no HAVEN')
  assert.throws(()=>readFileSync(sessionFile),{code:'ENOENT'})
  await c.fill('[name=handle]','sessao')
  await c.fill('[name=password]',pass)
  await c.click('Entrar')
  await c.visible('Olá, Sessão.')
  await c.click('Perfil e ajustes',true)
  await app.close()
  await c.click('Encerrar sessão')
  await c.visible('Entrar no HAVEN')
  assert.throws(()=>readFileSync(sessionFile),{code:'ENOENT'})
  console.log('PASS: persistência após fechar e reabrir, logout, revogação e saída offline.')
}catch(error){
  console.error(error.message)
  process.exitCode=1
}finally {
  for(const c of clients)c.ws.close()
  for(const child of children)child.kill()
  await app.close()
  db.close()
}
