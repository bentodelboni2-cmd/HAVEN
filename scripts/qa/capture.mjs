    await first.click('Ouvir chamada',true)
    await wait(250)
    assert.equal(await first.evalJs('window.qaCueStarts'),0,'sons do HAVEN pausados durante compartilhamento de áudio')
    await second.evalJs(`(async()=>{
      const stream=[...document.querySelectorAll('audio')].find(a=>!a.muted&&a.srcObject?.getAudioTracks().some(t=>t.enabled&&t.readyState==='live'))?.srcObject
      const track=stream?.getAudioTracks().find(t=>t.readyState==='live')
      if(!track)return null
      const ctx=new AudioContext(); await ctx.resume()
      const source=ctx.createMediaStreamSource(new MediaStream([track]))
      const a=ctx.createAnalyser(); a.fftSize=8192; source.connect(a)
      window.measureCapture=async ()=>{
        const samples=[]
        const data=new Float32Array(a.frequencyBinCount)
        const peak=frequency=>{
          const bin=Math.round(frequency*a.fftSize/ctx.sampleRate)
          return Math.max(-110,...data.slice(bin-1,bin+2))
        }
        for(let i=0;i<8;i++){
          await new Promise(resolve=>setTimeout(resolve,100))
          a.getFloatFrequencyData(data)
          samples.push([peak(440),peak(920)])
        }
        return samples[0].map((_,i)=>Math.round(samples.map(values=>values[i]).sort((x,y)=>x-y)[4]))
      }
    })()`)
