    await first.evalJs(`(async()=>{const ctx=new AudioContext();await ctx.resume();const osc=ctx.createOscillator();const gain=ctx.createGain();osc.frequency.value=920;gain.gain.value=.10;osc.connect(gain).connect(ctx.destination);osc.start();setTimeout(()=>{osc.stop();void ctx.close()},6500)})()`)
